/**
 * Composants classés « Extensions » (optionnels, hors UI Material cœur).
 * Doivent aussi figurer dans COMPONENT_NAMES / COMPONENT_CONFIG.
 * SwipeDeck est ajouté lors de sa création (Phase 3).
 */
export const EXTENSION_COMPONENT_NAMES = [
    'QrCode',
    'BarCode',
    'Signature',
    'Firework',
    'Confetti',
    'Snow',
    'Halo',
    'Holo',
    'Gradient',
    'SwipeDeck',
] as const satisfies readonly ComponentName[];

export type ExtensionComponentName = (typeof EXTENSION_COMPONENT_NAMES)[number];

/**
 * Indique si un nom de composant appartient à la couche Extensions.
 */
export function isExtensionComponent(name: string): name is ExtensionComponentName {
    return (EXTENSION_COMPONENT_NAMES as readonly string[]).includes(name);
}

