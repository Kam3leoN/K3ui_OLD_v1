/**
 * Extrait la clé numérique d'une forme `svg-N`
 * @param shape Nom de forme (ex. svg-3)
 */
export function parseSvgShapeKey(shape: string): string {
    if (shape.indexOf('svg-') === 0) {
        return shape.slice(4);
    }
    return shape;
}

/**
 * Renvoie le path plein d'un centre d'œil (ball)
 * @param shape Nom de forme (svg-N)
 */
export function getQrBallPath(shape: string): string {
    const key = parseSvgShapeKey(shape);
    return QR_BALL_SVG[key] ?? 'M0,0 H100 V100 H0 Z';
}

export interface QrFramePathInfo {
    dotted?: boolean;
    single?: string;
    outer?: string;
    inner?: string;
}

/**
 * Renvoie les infos de path pour un contour d'œil (frame)
 * @param shape Nom de forme (svg-N ou dotted)
 */
export function getQrFramePaths(shape: string): QrFramePathInfo {
    if (shape === 'dotted') {
        return { dotted: true };
    }
    if (shape.indexOf('svg-') === 0) {
        const key = parseSvgShapeKey(shape);
        if (QR_FRAME_SVG[key]) {
            return { single: QR_FRAME_SVG[key] };
        }
    }
    return {};
}

/**
 * Encode un SVG texte en data URL base64
 * @param svgText Contenu SVG
 */
export function svgTextToDataUrl(svgText: string): string {
    return `data:image/svg+xml;base64,${btoa(unescape(encodeURIComponent(svgText)))}`;
}

